"""Write the mapped LED geometry as a C header for the firmware.

Two structures, both in compressed sparse row form:
- the LED graph: every pair of LEDs closer than --radius (in LED spacings), weighted by a
  Gaussian of their distance, indexed by output * LEDS + index;
- a sphere fitted to the LEDs, as an icosphere mesh for simulations, plus per-LED weights for
  reading the simulation back out smoothly at each LED's direction from the centre.

    uv run tools/export_graph.py
"""

import argparse
from pathlib import Path

import numpy as np
import polars as pl
from scipy.optimize import least_squares
from scipy.spatial import cKDTree

ROOT = Path(__file__).resolve().parent.parent


def icosphere(level: int) -> tuple[np.ndarray, np.ndarray]:
    t = (1 + 5**0.5) / 2
    verts = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t),
             (0, -1, -t), (0, 1, -t), (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    faces = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4),
             (11, 10, 2), (10, 7, 6), (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8),
             (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)]
    verts = [np.array(v) / np.linalg.norm(v) for v in verts]
    for _ in range(level):
        midpoints, finer = {}, []

        def mid(a, b):
            key = (min(a, b), max(a, b))
            if key not in midpoints:
                m = verts[a] + verts[b]
                verts.append(m / np.linalg.norm(m))
                midpoints[key] = len(verts) - 1
            return midpoints[key]

        for a, b, c in faces:
            ab, bc, ca = mid(a, b), mid(b, c), mid(c, a)
            finer += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        faces = finer
    return np.array(verts), np.array(faces)


def csr(rows: np.ndarray, n: int) -> np.ndarray:
    """Row offsets for entries already sorted by row."""
    return np.searchsorted(rows, np.arange(n + 1))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--radius", type=float, default=1.25)
    p.add_argument("--sphere-level", type=int, default=3, help="icosphere subdivisions (3 = 642 vertices)")
    p.add_argument("--blur", type=float, default=0.5, help="LED sampling radius, in LED spacings")
    args = p.parse_args()

    df = pl.read_parquet(ROOT / "mapping" / "positions.parquet").sort("output", "index")
    leds_per_output = df["index"].max() + 1
    outputs = df["output"].max() + 1
    assert len(df) == outputs * leds_per_output, "positions must cover every LED"
    pts = df.select("x", "y", "z").to_numpy()

    pairs = cKDTree(pts).query_pairs(args.radius, output_type="ndarray")
    pairs = np.concatenate([pairs, pairs[:, ::-1]])
    pairs = pairs[np.lexsort((pairs[:, 1], pairs[:, 0]))]
    dist = np.linalg.norm(pts[pairs[:, 0]] - pts[pairs[:, 1]], axis=1)
    weight = np.exp(-((dist / (0.6 * args.radius)) ** 2))
    offsets = csr(pairs[:, 0], len(pts))
    degree = np.diff(offsets)

    fit = least_squares(lambda q: np.linalg.norm(pts - q[:3], axis=1) - q[3], [0, 0, 0, 2])
    centre, radius = fit.x[:3], fit.x[3]
    verts, faces = icosphere(args.sphere_level)
    edges = np.concatenate([faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]])
    edges = np.unique(np.concatenate([edges, edges[:, ::-1]]), axis=0)  # sorted by source
    mesh_offsets = csr(edges[:, 0], len(verts))

    # Each LED reads a Gaussian-weighted blend of the mesh vertices around its direction.
    dirs = (pts - centre) / np.linalg.norm(pts - centre, axis=1, keepdims=True)
    sigma = args.blur / radius  # radians on the unit sphere
    arc = np.arccos(np.clip(dirs @ verts.T, -1, 1))
    led_rows, mesh_cols = np.nonzero(arc < 2 * sigma)
    sample_w = np.exp(-((arc[led_rows, mesh_cols] / sigma) ** 2))
    sample_w /= np.bincount(led_rows, sample_w)[led_rows]
    sample_offsets = csr(led_rows, len(pts))

    fmt = lambda xs, f: ",".join(f.format(x) for x in xs)
    header = f"""// Generated by tools/export_graph.py from mapping/positions.parquet; do not edit.
#pragma once
#include <stdint.h>

constexpr int GRAPH_NODES = {len(pts)};
constexpr int GRAPH_EDGES = {len(pairs)};
// Position of each node in LED spacings, centred on the lantern.
const float GRAPH_POS[GRAPH_NODES][3] = {{{",".join("{" + fmt(p, "{:.3f}f") + "}" for p in pts)}}};
const uint16_t GRAPH_OFFSETS[GRAPH_NODES + 1] = {{{fmt(offsets, "{}")}}};
const uint8_t GRAPH_NEIGHBOURS[GRAPH_EDGES] = {{{fmt(pairs[:, 1], "{}")}}};
const float GRAPH_WEIGHTS[GRAPH_EDGES] = {{{fmt(weight, "{:.4f}f")}}};

// Sphere fitted to the LEDs (radius {radius:.2f} LED spacings), meshed as an icosphere.
constexpr int SPHERE_VERTS = {len(verts)};
constexpr int SPHERE_EDGES = {len(edges)};
constexpr int SPHERE_SAMPLES = {len(led_rows)};
const float SPHERE_POS[SPHERE_VERTS][3] = {{{",".join("{" + fmt(v, "{:.4f}f") + "}" for v in verts)}}};
const uint16_t SPHERE_OFFSETS[SPHERE_VERTS + 1] = {{{fmt(mesh_offsets, "{}")}}};
const uint16_t SPHERE_NEIGHBOURS[SPHERE_EDGES] = {{{fmt(edges[:, 1], "{}")}}};
// For each LED, the mesh vertices it blends and their weights (summing to 1).
const uint16_t SAMPLE_OFFSETS[GRAPH_NODES + 1] = {{{fmt(sample_offsets, "{}")}}};
const uint16_t SAMPLE_VERTS[SPHERE_SAMPLES] = {{{fmt(mesh_cols, "{}")}}};
const float SAMPLE_WEIGHTS[SPHERE_SAMPLES] = {{{fmt(sample_w, "{:.4f}f")}}};
"""
    out = ROOT / "src" / "lantern_graph.h"
    out.write_text(header)
    print(f"{len(pts)} nodes, {len(pairs) // 2} links, degree min {degree.min()} median {int(np.median(degree))} "
          f"max {degree.max()}")
    per_led = np.diff(sample_offsets)
    print(f"sphere radius {radius:.2f}, {len(verts)} vertices, {len(edges) // 2} edges; "
          f"vertices blended per LED min {per_led.min()} median {int(np.median(per_led))}; wrote {out}")


if __name__ == "__main__":
    main()
