"""Write colour maps as a C header for the firmware, sampled from matplotlib and gamma-corrected
the way FastLED's dim8_video does, so the firmware can interpolate them linearly.

    uv run tools/export_colormaps.py
"""

from pathlib import Path

import matplotlib
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
STOPS = 32
# (name, cyclic); cyclic maps wrap, so their last stop leads back into the first.
MAPS = [("twilight", True), ("magma", False), ("inferno", False), ("viridis", False), ("ember", False)]


def ember(t: np.ndarray) -> np.ndarray:
    """Dark troughs, red to amber fronts, blue cores; already in LED output values."""
    stops = np.array([[0, 0, 0, 0], [0.5, 0, 0, 0], [0.65, 140, 0, 0], [0.8, 255, 90, 0], [0.9, 60, 0, 160], [1, 0, 60, 255]])
    return np.stack([np.interp(t, stops[:, 0], stops[:, c]) for c in (1, 2, 3)], axis=1).round()


def dim8_video(x: np.ndarray) -> np.ndarray:
    return np.where(x > 0, np.floor(x * x / 256) + 1, 0)


def main() -> None:
    rows = []
    for name, cyclic in MAPS:
        t = np.arange(STOPS) / (STOPS if cyclic else STOPS - 1)
        rgb = ember(t) if name == "ember" else dim8_video(np.round(255 * matplotlib.colormaps[name](t)[:, :3]))
        stops = ",".join("{%d,%d,%d}" % tuple(c) for c in rgb.astype(int))
        rows.append(f'    {{"{name}", {str(cyclic).lower()}, {{{stops}}}}},')
    header = f"""// Generated by tools/export_colormaps.py; do not edit.
#pragma once
#include <stdint.h>

constexpr int COLORMAP_STOPS = {STOPS};
struct Colormap {{
    const char *name;
    bool cyclic;
    uint8_t stops[COLORMAP_STOPS][3];
}};
enum {{ {", ".join(n.upper() for n, _ in MAPS)}, COLORMAPS }};
const Colormap COLORMAP[COLORMAPS] = {{
{chr(10).join(rows)}
}};
"""
    (ROOT / "src" / "colormaps.h").write_text(header)


if __name__ == "__main__":
    main()
